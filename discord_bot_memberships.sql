create table if not exists public.discord_bot_memberships (
  id bigint generated by default as identity primary key,
  discord_user_id text not null,
  provider text not null,
  provider_user_id text,
  username text,
  plan_key text,
  is_trial boolean not null default false,
  is_lifetime boolean not null default false,
  expires_at timestamptz,
  connections integer,
  role_id text,
  parent_membership_id bigint references public.discord_bot_memberships(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (discord_user_id, provider, provider_user_id)
);
create index if not exists idx_discord_bot_memberships_user on public.discord_bot_memberships(discord_user_id);
create index if not exists idx_discord_bot_memberships_provider on public.discord_bot_memberships(provider);
alter table public.discord_bot_memberships enable row level security;
