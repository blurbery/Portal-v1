-- Run once in the portal's Supabase project.
-- Values are AES-256-GCM encrypted by portal/server.js before storage.
create table if not exists public.portal_settings (
  key_name text primary key,
  value_encrypted text not null,
  is_secret boolean not null default false,
  updated_at timestamptz not null default now()
);

alter table public.portal_settings enable row level security;

-- The portal uses the Supabase service-role key server-side. No browser/client
-- policy is intentionally provided for this table.

-- Member issue reports used by the optional Requests → Report issues feature.
create table if not exists public.portal_issue_reports (
  id bigint generated by default as identity primary key,
  discord_user_id text,
  username text,
  subject text not null,
  details text not null,
  status text not null default 'open',
  created_at timestamptz not null default now()
);

alter table public.portal_issue_reports enable row level security;
